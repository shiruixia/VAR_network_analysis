def save_main_figure() -> Path:
    """Save the combined six-panel manuscript Figure 1."""
    output = MAIN_OUTPUT_DIR / "figure1_main.png"
    fig = plt.figure(figsize=MAIN_FIGSIZE)
    grid = fig.add_gridspec(3, 3, width_ratios=[1, 1, 0.48], wspace=0.12, hspace=0.18)
    axes = [
        fig.add_subplot(grid[0, 0]),
        fig.add_subplot(grid[0, 1]),
        fig.add_subplot(grid[1, 0]),
        fig.add_subplot(grid[1, 1]),
        fig.add_subplot(grid[2, 0]),
        fig.add_subplot(grid[2, 1]),
    ]
    legend_ax = fig.add_subplot(grid[:, 2])
    for ax, spec in zip(axes, PANEL_SPECS):
        draw_network_panel(ax, spec, add_panel_label=True)
    draw_shared_legend(legend_ax)
    fig.savefig(output, dpi=300, bbox_inches="tight", facecolor="white")
    fig.savefig(output.with_suffix(".pdf"), dpi=300, bbox_inches="tight", facecolor="white")
    fig.savefig(output.with_suffix(".eps"), dpi=300, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return output


def main() -> None:
    PANEL_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    MAIN_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for spec in PANEL_SPECS:
        save_single_panel(spec, PANEL_OUTPUT_DIR)
    main_output = save_main_figure()
    print(f"Figure1 panels: {PANEL_OUTPUT_DIR}")
    print(f"Figure1 main: {main_output}")
    print(f"Figure1 main EPS: {main_output.with_suffix('.eps')}")


if __name__ == "__main__":
    main()
