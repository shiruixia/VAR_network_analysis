# -*- coding: utf-8 -*-
"""Create manuscript Figure 1 from precomputed Figure1 network results.

Visualization only. This script reads ``figure1/result`` workbooks generated by
the dataset pipelines and writes the six panel images plus the combined paper
figure. It does not read source match workbooks and does not recompute network
statistics.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


FIGURE1_ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = Path(__file__).resolve().parent
RESULT_ROOT = FIGURE1_ROOT / "result"
PANEL_OUTPUT_DIR = FIGURE1_ROOT / "panels"
MAIN_OUTPUT_DIR = FIGURE1_ROOT
MAIN_FIGSIZE = (13.6, 13.2)

if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from utils.indicator_config import MATCH_INDICATORS
from utils.network_plotting import draw_network_panel, draw_shared_legend, save_single_panel


@dataclass(frozen=True)
class PanelSpec:
    panel: str
    dataset: str
    period: str
    title: str
    correlation_workbook: Path
    edge_workbook: Path
    sheet_name: str
    output_png: str
    node_order: list[str]


def dataset_result_path(dataset: str, filename: str) -> Path:
    return RESULT_ROOT / dataset / filename


